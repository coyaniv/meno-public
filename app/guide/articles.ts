/**
 * What the site is allowed to show. The filter lives here, at the source, rather
 * than at each call site — six places consume this list (home, guide index, topic
 * pages, article page, sitemap, llms.txt) and a seventh will be added eventually.
 * Filtering per call site means an unreviewed draft goes live the first time
 * someone forgets one.
 */
export const ARTICLES: Article[] = ALL_ARTICLES.filter((a) => a.published);

/**
 * Clusters that still have something in them. Unpublishing a guide can empty a
 * cluster out, and an empty cluster page is a thin page with a dead pillar link
 * and a CollectionPage schema listing nothing — so it must not be built at all.
 */
export const CLUSTERS = ALL_CLUSTERS.filter((c) =>
  ARTICLES.some((a) => a.cluster === c.id)
);

/**
 * Drafts are readable at their real URL under `next dev`, so a guide can be
 * proofread in place before it goes live. This deliberately does NOT widen
 * ARTICLES: the draft stays out of the index, the sitemap, llms.txt and the
 * cluster pages, and `next build` runs with NODE_ENV=production, so a draft can
 * never be exported. Preview is a local reading affordance, not a publish path.
 */
const PREVIEW_DRAFTS = process.env.NODE_ENV === "development";

/**
 * The slugs `/guide/[slug]` is allowed to render. Identical to ARTICLES in any
 * production build; only `next dev` widens it to include drafts. It is separate
 * from ARTICLES so that widening preview can never widen the sitemap.
 */
export const RENDERABLE_ARTICLES: Article[] = PREVIEW_DRAFTS
  ? ALL_ARTICLES
  : ARTICLES;

export function getArticle(slug: string): Article | undefined {
  return RENDERABLE_ARTICLES.find((a) => a.slug === slug);
}
